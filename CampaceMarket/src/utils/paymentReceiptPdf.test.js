import test from 'node:test';
import assert from 'node:assert/strict';
import {
  buildPaymentReceiptPdf,
  paymentReceiptPdfFilename,
} from './paymentReceiptPdf.js';

test('builds a one-page branded receipt with item, fee, and settlement totals', () => {
  const pdf = buildPaymentReceiptPdf({
    receipt_number: 'RCPT-20261105-0061',
    order_number: 61,
    payment_date: '2026-11-05T12:00:00Z',
    buyer_name: 'Buyer Name',
    seller_name: 'Seller Name',
    product_name: 'Laptop',
    quantity: 1,
    unit_price: 30000,
    item_total: 30000,
    fees: 1050,
    platform_commission_percent: 3.5,
    total_paid: 30000,
    payment_method: 'Chapa Split Payment',
    transaction_reference: 'CHAPA-REF-61',
    payment_status: 'Successful',
  });
  const output = pdf.output();

  assert.equal(pdf.getNumberOfPages(), 1);
  assert.match(output, /UniXchange/u);
  assert.match(output, /Official Transaction Receipt/u);
  assert.match(output, /Chapa Split Payment/u);
  assert.match(output, /30,000\.00 ETB/u);
  assert.match(output, /1,050\.00 ETB/u);
  assert.match(output, /28,950\.00 ETB/u);
  assert.match(output, /Official digital receipt generated by UniXchange/u);
  assert.equal(paymentReceiptPdfFilename(61), 'Campus-Market-Order-61-Receipt.pdf');
});
